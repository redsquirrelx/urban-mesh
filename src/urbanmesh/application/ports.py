"""Application-owned ports; implementations supplied at bootstrap."""
from typing import Protocol
from datetime import date
from urbanmesh.domain.models import (Route, Bicycle, Ride, FareQuote, PaymentReceipt,
    Ticket, SensorReading, QualityResult, CustodyEvent, Notice, RepairTicket,
    StockItem, Boarding)

class RouteSource(Protocol):
    def get(self, route_id: str) -> Route | None: ...
    def all_routes(self) -> list[Route]: ...
    def connecting(self, origin: str, destination: str) -> list[tuple[Route, int]]: ...

class BicycleCatalog(Protocol):
    def find(self, bike_id: str) -> Bicycle | None: ...
    def available_at(self, station_id: str) -> list[Bicycle]: ...

class LockGateway(Protocol):
    def unlock(self, bike_id: str) -> bool: ...
    def lock(self, bike_id: str) -> bool: ...

class RideRepository(Protocol):
    def save(self, ride: Ride) -> None: ...
    def find(self, ride_id: str) -> Ride | None: ...

class FarePolicy(Protocol):
    def quote(self, ride: Ride) -> FareQuote: ...

class PaymentGateway(Protocol):
    def capture(self, quote: FareQuote) -> PaymentReceipt: ...

class TicketStore(Protocol):
    def save(self, ticket: Ticket) -> None: ...
    def find(self, ticket_id: str) -> Ticket | None: ...

class AuditSink(Protocol):
    def append(self, event: dict) -> None: ...

class CampaignQueue(Protocol):
    def enqueue(self, rider_id: str, offer_code: str) -> None: ...

class MessageGateway(Protocol):
    def send(self, recipient: str, text: str) -> None: ...

class RepairQueue(Protocol):
    def enqueue(self, ticket: RepairTicket) -> None: ...

class BoardingStore(Protocol):
    def read_all(self) -> list[Boarding]: ...
    def delete_before(self, cutoff: date) -> int: ...

class ShiftFlags(Protocol):
    def flag(self, driver_id: str, status: str) -> None: ...

class SensorReader(Protocol):
    def read(self, sensor_id: str) -> SensorReading: ...

class QualityRule(Protocol):
    def assess(self, reading: SensorReading) -> str: ...

class QualityStore(Protocol):
    def save(self, result: QualityResult) -> None: ...
    def find(self, sensor_id: str) -> QualityResult | None: ...
    def list_all(self) -> list[QualityResult]: ...

class CustodySink(Protocol):
    def append(self, event: CustodyEvent) -> None: ...
    def list_events(self) -> list[CustodyEvent]: ...

class RetentionStore(Protocol):
    def list_before(self, cutoff: date) -> list[SensorReading]: ...
    def delete_before(self, cutoff: date) -> int: ...

class InventoryCatalog(Protocol):
    def list_items(self) -> list[StockItem]: ...
    def find(self, sku: str) -> StockItem | None: ...
    def save(self, item: StockItem) -> None: ...
    def remove(self, sku: str) -> bool: ...

class SupplyOrderStore(Protocol):
    def save(self, order: object) -> None: ...
    def find(self, order_id: str) -> object | None: ...

class PromotionSource(Protocol):
    def find(self, code: str) -> object | None: ...

class DeliveryRateProvider(Protocol):
    def price_cents(self, parcel: object) -> int: ...

class SupplyQuoteStore(Protocol):
    def save(self, quote: object) -> None: ...
    def find(self, quote_id: str) -> object | None: ...

class QuoteIds(Protocol):
    def new_id(self) -> str: ...
